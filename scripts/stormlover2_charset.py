def decode_u16(vals):
    n = len(CHARSET)
    out = []
    for v in vals:
        if v >= CTRL_THRESHOLD:
            out.append('\x00')
        elif v in SPECIAL:
            out.append(SPECIAL[v])
        elif 0 <= v < n:
            out.append(CHARSET[v])
        else:
            out.append('\u3013')
    return ''.join(out)



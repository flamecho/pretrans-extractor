def decode_u16(vals, undecoded='\u3014\u672a\u89e3\u6790\u3015'):
    """u16 码流 → 文本（调试用；提取器用 stormlover_natsu_run.toks）。"""
    n = len(CHARSET)
    out = []
    for v in vals:
        if v >= 0xFF00:
            out.append('\x00')
        elif v in SPECIAL:
            out.append(SPECIAL[v])
        elif v in DECO:
            out.append('')
        elif 0 <= v < n:
            out.append(CHARSET[v])
        else:
            out.append(undecoded)
    return ''.join(out)



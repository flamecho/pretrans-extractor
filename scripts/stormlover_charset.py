CTRL_THRESHOLD = 0xFF00

def decode_u16(vals):
    """u16 码流 → 文本；code>=0xFF00 视为控制码，输出 \\x00 占位（由调用方切分）。"""
    n = len(CHARSET)
    out = []
    for v in vals:
        if v >= CTRL_THRESHOLD:
            out.append('\x00')
        elif v in SPECIAL:
            out.append(SPECIAL[v])
        elif 0 <= v < n:
            out.append(CHARSET[v])
        else:
            out.append('\u3013')
    return ''.join(out)


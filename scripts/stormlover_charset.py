import struct

SKIP_CODES = [(0x81FC, 0x81FC), (0x839F, 0x83D7), (0x8440, 0x8492), (0x849F, 0x849F)]

def build_charset():
    out = []
    for lead in list(range(0x81, 0xA0)) + list(range(0xE0, 0xFD)):
        for trail in list(range(0x40, 0x7F)) + list(range(0x80, 0xFD)):
            v = (lead << 8) | trail
            if any(a <= v <= b for a, b in SKIP_CODES):
                continue
            try:
                s = bytes([lead, trail]).decode('cp932')
            except Exception:
                continue
            if len(s) == 1:
                out.append(s)
    return out


def decompress(src, dst_len):
    dst = bytearray()
    pos = 8
    mask = 8
    bit = 1
    flag = src[pos] ^ XOR[mask & 0xff]; pos += 1; mask += 1
    while pos < len(src) and len(dst) < dst_len:
        if bit == 256:
            bit = 1
            flag = src[pos] ^ XOR[mask & 0xff]; pos += 1; mask += 1
        if flag & bit:
            dst.append(src[pos] ^ XOR[mask & 0xff]); pos += 1; mask += 1
        else:
            count = src[pos] ^ XOR[mask & 0xff]; pos += 1; mask += 1
            count += (src[pos] ^ XOR[mask & 0xff]) << 8; pos += 1; mask += 1
            repeat = len(dst) - ((count >> 4) - 1) - 1
            count = (count & 0x0f) + 2
            if repeat < 0 or repeat >= len(dst):
                raise ValueError(f'corrupt at src {pos} dst {len(dst)}')
            for i in range(count):
                dst.append(dst[repeat + i])
        bit <<= 1
    return bytes(dst)

def read_toc(d):
    toc = {}
    for i in range(10000):
        off, ln = struct.unpack_from('<II', d, i*8)
        if off:
            toc[i] = (off, ln)
    return toc

def scenario(d, off, ln):
    s = d[off:off+ln]
    hdr_len = struct.unpack_from('<I', s, 0)[0]
    ver = struct.unpack_from('<I', s, 4)[0]
    comp_off = struct.unpack_from('<I', s, 0x20)[0]
    dlen = struct.unpack_from('<I', s, 0x24)[0]
    clen = struct.unpack_from('<I', s, 0x28)[0]
    return hdr_len, ver, comp_off, dlen, clen, s

